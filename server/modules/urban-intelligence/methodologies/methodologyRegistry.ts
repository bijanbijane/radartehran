export function getIndicatorDefinitionById(indicatorId: string): IndicatorDefinitionRecord {
  const found = CANONICAL_URBAN_INDICATOR_DEFINITIONS.find((d) => d.indicatorId === indicatorId);
  if (!found) {
    throw new CoreApiError('NOT_FOUND', 404, `Urban indicator definition "${indicatorId}" is not registered.`);
  }
  return found;
}

export function assertCompatibleMeasurementUnit(
  indicatorId: string,
  suppliedUnit: MeasurementUnitCode,
): void {
  const def = getIndicatorDefinitionById(indicatorId);
  if (def.measurementUnit !== suppliedUnit) {
    throw new CoreApiError(
      'VALIDATION_FAILED',
      400,
      `Incompatible measurement unit "${suppliedUnit}" for indicator "${indicatorId}"; expected "${def.measurementUnit}".`,
    );
  }
}
