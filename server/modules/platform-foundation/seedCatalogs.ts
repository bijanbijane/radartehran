function buildOwnershipSeed(
  spec: ModuleSeedSpec,
  tenantScope: TenantOwnershipClassification,
): DomainOwnershipRecord {
  const entityType = spec.entities[0];
  const isPlanned = spec.implStatus === 'PLANNED';
  return {
    id: `own_${spec.emp.toLowerCase()}_${entityType.toLowerCase()}`,
    entityType,
    owningEmployee: spec.emp,
    owningModuleCode: sCode(spec),
    implementationState: isPlanned ? 'PLANNED_FUTURE_PHASE' : 'ESTABLISHED_OPERATIONAL',
    authoritativePersistenceProvider:
      spec.emp === 'EMP_63'
        ? 'OBJECT_STORAGE_R2_OR_LOCAL'
        : spec.emp === 'EMP_80'
          ? 'FILE_BACKED_DURABLE_JSON'
          : 'FIRESTORE_AUTHORITATIVE',
    authoritativeCollectionOrTable: `col_${entityType.toLowerCase()}`,
    mutationServiceReference: `${spec.code}.authoritativeMutationService`,
    readModelReferences: [`${spec.code}.readProjection`],
    derivedDataReferences: [`analytical-data-platform.${entityType.toLowerCase()}_fact`],
    replicationPolicy: 'ASYNC_EVENT_PROJECTION',
    reconciliationProcessReference: `platform-integration-resilience.reconcile.${entityType.toLowerCase()}`,
    retentionOwner: 'EMP_72',
    legalHoldPrecedenceEnforcedBy: 'EMP_72',
    tenantOwnershipClassification: tenantScope,
    consistencyClassification:
      spec.emp === 'EMP_54' || spec.emp === 'EMP_72'
        ? 'STRONG_TRANSACTIONAL'
        : 'TRANSACTIONAL_WITHIN_PROVIDER',
    versioningStrategy:
      spec.emp === 'EMP_54' ? 'APPEND_ONLY_IMMUTABLE' : 'OPTIMISTIC_RECORD_VERSION',
    version: 1,
    createdAt: SEED_TIMESTAMP,
    updatedAt: SEED_TIMESTAMP,
  };
}

function sCode(spec: ModuleSeedSpec): string {
  return spec.code;
}

